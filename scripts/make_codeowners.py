#!/usr/bin/env python3
"""Write .github/CODEOWNERS from .github/owners.json (fill github_users first)."""

import json
from pathlib import Path

o = json.loads(Path(".github/owners.json").read_text(encoding="utf-8"))
users = o["github_users"]
lines = ["# Generated by scripts/make_codeowners.py from .github/owners.json. Do not edit by hand.", ""]
for module, info in o["modules"].items():
    user = users.get(module, "").lstrip("@")
    if not user:
        lines.append(f"# {module}: no GitHub user set yet")
        continue
    for p in info["paths"]:
        pattern = "/" + p + ("**" if p.endswith("/") else "")
        lines.append(f"{pattern} @{user}")
Path(".github/CODEOWNERS").write_text("\n".join(lines) + "\n", encoding="utf-8")
print("Wrote .github/CODEOWNERS")
